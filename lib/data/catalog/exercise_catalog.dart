  static List<Exercise> all() => _all;

  /// Tree steps and the general library together: what a person searching
  /// for an exercise expects to be searching.
  static List<Exercise> everything() =>
      [..._all, ...ExerciseLibraryCatalog.all()];

  /// Everything you can *pick*, each movement listed once. A step is performed
  /// with a library movement — a bench dip is both the `dips` step and the
  /// movement `bench_dip` — so the movement is left out and the step stands
  /// for it. Picking the step puts the work on its skill tree; picking the
  /// twin would be the same exercise off the path.
  ///
  /// Browsing uses [everything] instead: a library that quietly drops entries
  /// is not a library.
  static List<Exercise> searchable() {
    final performedWith = _all.map((step) => step.libraryId).toSet();
    return [
      ..._all,
      ...ExerciseLibraryCatalog.all()
          .where((movement) => !performedWith.contains(movement.id)),
    ];
  }

  static List<Exercise> browsable() => _all
      .where((exercise) => SkillCategoryCatalog.isBrowsableId(
            _resolveSkillCategoryId(exercise),
          ))
      .toList();

  static List<Exercise> forCategory(ExerciseCategory category) =>
      _all.where((e) => e.category == category).toList()
        ..sort((a, b) => a.treeOrder.compareTo(b.treeOrder));

  static List<Exercise> forSkillCategory(String skillCategoryId) =>
      _all.where((e) => _resolveSkillCategoryId(e) == skillCategoryId).toList()
        ..sort((a, b) => a.treeOrder.compareTo(b.treeOrder));

  static int totalForCategory(ExerciseCategory category) =>
      _all.where((e) => e.category == category).length;

  static int totalForSkillCategory(String skillCategoryId) =>
      _all.where((e) => _resolveSkillCategoryId(e) == skillCategoryId).length;

  /// Any exercise by id, tree step or library movement. A logged set has to
  /// resolve back to something whichever half it came from.
  static Exercise? findById(String id) {
    for (final exercise in _all) {
      if (exercise.id == id) return exercise;
    }
    return ExerciseLibraryCatalog.findById(id);
  }

  static String skillCategoryIdForExercise(Exercise exercise) =>
      _resolveSkillCategoryId(exercise);

  static String _resolveSkillCategoryId(Exercise exercise) =>
      _normalizedSkillCategoryId(
        exercise.skillCategoryId.isEmpty
            ? exercise.category.id
            : exercise.skillCategoryId,
      );

  static String _normalizedSkillCategoryId(String skillCategoryId) {
    switch (skillCategoryId) {
      case SkillCategoryCatalog.lSitVSitId:
      case SkillCategoryCatalog.abWheelId:
      case SkillCategoryCatalog.legRaisesId:
        return SkillCategoryCatalog.coreId;
      default:
        return skillCategoryId;
    }
  }
